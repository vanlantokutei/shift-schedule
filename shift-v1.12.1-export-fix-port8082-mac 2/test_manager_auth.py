def test_csrf_cookie_logout_and_no_cache(env):
    c=setup(env);app,raw,_=env
    assert c.get('/',base_url='https://localhost').data==b'PRIVATE_SCHEDULE'
    assert c.post('/shift',json={},base_url='https://localhost').status_code==403
    token=csrf(c,'/admin/accounts')
    assert c.post('/shift',json={},headers={'X-CSRF-Token':token},base_url='https://localhost').status_code==200
    r=c.get('/admin/accounts',base_url='https://localhost')
    assert r.headers['Cache-Control']=='no-store, private'
    assert r.headers['X-Frame-Options']=='DENY'
    cookie=c.get_cookie('betoya_manager')
    assert cookie.secure and cookie.http_only and cookie.same_site=='Lax'
    assert post(c,'/admin/logout',{'csrf_token':token}).status_code==302
    assert c.get('/',base_url='https://localhost').status_code==302


def test_invitation_activation_permissions_and_revocation(env):
    owner=setup(env);app,raw,_=env
    token=csrf(owner,'/admin/accounts')
    r=post(owner,'/admin/accounts',dict(csrf_token=token,username='manager2',display_name='Quản lý 2'))
    assert r.status_code==200
    invite=re.search(rb'value="https://localhost/admin/activate#([^"]+)"',r.data).group(1).decode()
    manager=app.test_client()
    activation_csrf=csrf(manager,'/admin/activate')
    data=dict(csrf_token=activation_csrf,invite_token=invite,password='manager-secret-123',confirm_password='manager-secret-123')
    assert post(manager,'/admin/activate',data).status_code==302
    data['csrf_token']=csrf(manager,'/admin/activate')
    assert post(manager,'/admin/activate',data).status_code==400
    r=post(manager,'/admin/login',dict(csrf_token=csrf(manager),username='manager2',password='manager-secret-123'))
    assert r.status_code==302
    assert manager.get('/',base_url='https://localhost').status_code==200
    assert manager.get('/admin/accounts',base_url='https://localhost').status_code==403
    uid=raw.execute("SELECT id FROM manager_accounts WHERE username='manager2'").fetchone()['id']
    assert post(owner,f'/admin/accounts/{uid}/disable',{'csrf_token':token}).status_code==302
    assert manager.get('/',base_url='https://localhost').status_code==302


