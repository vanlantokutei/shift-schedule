class LocalConnection:
    def __init__(self, raw): self.raw=raw
    def __enter__(self): return self
    def __exit__(self,*args):
        self.raw.rollback() if args[0] else self.raw.commit()
    def execute(self,sql,args=()):
        if 'pg_advisory_xact_lock' in sql:
            return self.raw.execute('SELECT 1')
        sql=sql.replace('INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY','INTEGER PRIMARY KEY AUTOINCREMENT')
        sql=sql.replace("CURRENT_TIMESTAMP + interval '15 minutes'","datetime(CURRENT_TIMESTAMP, '+15 minutes')")
        sql=sql.replace("CURRENT_TIMESTAMP + interval '48 hours'","datetime(CURRENT_TIMESTAMP, '+48 hours')")
        return self.raw.execute(sql.replace('%s','?'),args)


