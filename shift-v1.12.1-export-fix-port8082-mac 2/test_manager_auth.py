def csrf(client,path='/admin/login'):
    r=client.get(path,base_url='https://localhost')
    match=re.search(rb'name="csrf_token" value="([^"]+)"',r.data)
    return match.group(1).decode() if match else None


def post(client,path,data):
    return client.post(path,data=data,base_url='https://localhost')


def setup(env):
    app,raw,monkeypatch=env
    monkeypatch.setenv('ADMIN_SETUP_TOKEN','a'*40)
    c=app.test_client()
    r=post(c,'/admin/setup',dict(csrf_token=csrf(c,'/admin/setup'),setup_token='a'*40,username='owner',display_name='Lân',password='test-owner-password',confirm_password='test-owner-password'))
    assert r.status_code==302
    r=post(c,'/admin/login',dict(csrf_token=csrf(c),username='owner',password='test-owner-password'))
    assert r.status_code==302
    return c


def test_all_management_routes_are_closed(env):
    app,raw,_=env;c=app.test_client()
    for path in ['/','/month','/backup.csv','/draft-preview','/kibo/status','/admin/accounts']:
        r=c.get(path,base_url='https://localhost');assert r.status_code==302
        assert r.headers['Location'].endswith('/admin/login')
        assert b'PRIVATE' not in r.data
    for path in ['/shift','/staff','/staff/reorder','/move-week','/restore-backup']:
        assert c.post(path,json={},base_url='https://localhost').status_code==401
    for path in ['/kibo','/kibo/prefill','/healthz']:
        assert c.get(path,base_url='https://localhost').status_code==200
    assert post(c,'/kibo',{}).status_code==200
    assert post(c,'/kibo/fixed',{}).status_code==200
    assert c.delete('/kibo/fixed',base_url='https://localhost').status_code==200


