"""Manager-only authentication; employee availability intake stays public."""
import hashlib
import hmac
import os
import re
import secrets
from datetime import timedelta
from flask import abort, g, jsonify, redirect, render_template, request, session, url_for
from werkzeug.security import check_password_hash, generate_password_hash


def install_manager_auth(app, connect):
    app.config.update(SESSION_COOKIE_NAME='betoya_manager', SESSION_COOKIE_SECURE=True,
                      SESSION_COOKIE_HTTPONLY=True, SESSION_COOKIE_SAMESITE='Lax',
                      PERMANENT_SESSION_LIFETIME=timedelta(hours=12),
                      SESSION_REFRESH_EACH_REQUEST=False)
    with connect() as c:
        c.execute('SELECT pg_advisory_xact_lock(72905431)')
        c.execute('CREATE TABLE IF NOT EXISTS manager_auth_config (key TEXT PRIMARY KEY, value TEXT NOT NULL)')
        c.execute('INSERT INTO manager_auth_config(key,value) VALUES(%s,%s) ON CONFLICT(key) DO NOTHING',
                  ('session_secret', secrets.token_hex(32)))
        app.secret_key = c.execute('SELECT value FROM manager_auth_config WHERE key=%s', ('session_secret',)).fetchone()['value']
        c.execute('''CREATE TABLE IF NOT EXISTS manager_accounts (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL, display_name TEXT NOT NULL,
            password_hash TEXT, role TEXT NOT NULL DEFAULT 'manager',
            active INTEGER NOT NULL DEFAULT 1, version INTEGER NOT NULL DEFAULT 1,
            invite_hash TEXT UNIQUE, invite_expires TIMESTAMPTZ,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)''')
        c.execute('''CREATE TABLE IF NOT EXISTS manager_login_limits (
            bucket TEXT PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0,
            reset_at TIMESTAMPTZ NOT NULL)''')

    dummy_hash = generate_password_hash(secrets.token_urlsafe(32))
    public_endpoints = {'static', 'kibo', 'kibo_prefill', 'kibo_fixed', 'kibo_fixed_delete',
                        'manager_login', 'manager_setup', 'manager_activate', 'healthz'}

    def csrf():
        if 'csrf' not in session:
            session['csrf'] = secrets.token_urlsafe(32)
        return session['csrf']

    app.jinja_env.globals['manager_csrf'] = csrf

    def limited(label, maximum=10):
        bucket = hmac.new(app.secret_key.encode(), label.encode(), hashlib.sha256).hexdigest()
        with connect() as c:
            row = c.execute('''INSERT INTO manager_login_limits(bucket,attempts,reset_at)
                VALUES(%s,1,CURRENT_TIMESTAMP + interval '15 minutes')
                ON CONFLICT(bucket) DO UPDATE SET
                  attempts=CASE WHEN manager_login_limits.reset_at<=CURRENT_TIMESTAMP THEN 1 ELSE manager_login_limits.attempts+1 END,
                  reset_at=CASE WHEN manager_login_limits.reset_at<=CURRENT_TIMESTAMP THEN CURRENT_TIMESTAMP + interval '15 minutes' ELSE manager_login_limits.reset_at END
                RETURNING attempts''', (bucket,)).fetchone()
        return row['attempts'] > maximum

    def has_owner():
        with connect() as c:
            return c.execute("SELECT id FROM manager_accounts WHERE role='owner' LIMIT 1").fetchone() is not None

    def page(mode, error=None, **kw):
        return render_template('manager_auth.html', mode=mode, error=error, **kw)

    def valid_account(username, display_name):
        return bool(re.fullmatch(r'[a-z0-9][a-z0-9_.-]{2,39}', username)) and 1 <= len(display_name) <= 80

    def password_error():
        password = request.form.get('password', '')
        if not 12 <= len(password) <= 128:
            return 'Mật khẩu cần từ 12 đến 128 ký tự.'
        if password != request.form.get('confirm_password', ''):
            return 'Hai mật khẩu chưa giống nhau.'

    @app.before_request
    def protect_manager():
        g.manager = None
        if request.endpoint is None:
            return
        # Public Kibo does not use manager authority or manager sessions for writes.
        if request.endpoint in {'static','kibo','kibo_prefill','kibo_fixed','kibo_fixed_delete','healthz'}:
            return
        uid = session.get('manager_id')
        if uid:
            with connect() as c:
                user = c.execute('SELECT id,username,display_name,role,active,version FROM manager_accounts WHERE id=%s', (uid,)).fetchone()
            if user and user['active'] and user['version'] == session.get('manager_version'):
                g.manager = user
            else:
                session.clear()
        if request.endpoint not in public_endpoints and not g.manager:
            if request.method not in {'GET','HEAD','OPTIONS'} or request.is_json:
                return jsonify(ok=False,error='Cần đăng nhập quản lý.',login_url=url_for('manager_login')),401
            return redirect(url_for('manager_login'))
        if request.method not in {'GET','HEAD','OPTIONS'}:
            supplied = request.headers.get('X-CSRF-Token') or request.form.get('csrf_token','')
            expected = session.get('csrf','')
            if not expected or not hmac.compare_digest(expected, supplied):
                return jsonify(ok=False,error='Phiên bảo mật đã hết hạn. Vui lòng tải lại trang.'),403
        if request.endpoint in {'manager_accounts','manager_account_action'} and g.manager['role'] != 'owner':
            abort(403)

    @app.after_request
    def security_headers(response):
        response.headers['X-Content-Type-Options'] = 'nosniff'
        response.headers['X-Frame-Options'] = 'DENY'
        response.headers['Referrer-Policy'] = 'no-referrer'
        response.headers['Strict-Transport-Security'] = 'max-age=31536000'
        if request.endpoint != 'static':
            response.headers['Cache-Control'] = 'no-store, private'
        return response

    @app.get('/healthz')
    def healthz():
        return jsonify(ok=True)

    @app.route('/admin/login', methods=['GET','POST'])
    def manager_login():
        if g.manager:
            return redirect(url_for('index'))
        if request.method == 'POST':
            username = request.form.get('username','').strip().lower()[:100]
            if limited('login-address:' + (request.remote_addr or ''), maximum=100) or limited('login:' + username):
                return page('login', 'Đã thử quá nhiều lần. Vui lòng đợi 15 phút.'),429
            with connect() as c:
                user = c.execute('SELECT * FROM manager_accounts WHERE username=%s', (username,)).fetchone()
            password = request.form.get('password','')
            matched = check_password_hash((user['password_hash'] if user else None) or dummy_hash, password[:129])
            if user and user['active'] and user['password_hash'] and matched and len(password)<=128:
                session.clear()
                session.permanent = True
                session['manager_id'] = user['id']
                session['manager_version'] = user['version']
                csrf()
                return redirect(url_for('index'))
            return page('login', 'Tên đăng nhập hoặc mật khẩu không đúng.'),401
        return page('login', setup_available=not has_owner())

    @app.post('/admin/logout')
    def manager_logout():
        session.clear()
        return redirect(url_for('manager_login'))

    @app.route('/admin/setup', methods=['GET','POST'])
    def manager_setup():
        if has_owner():
            return redirect(url_for('manager_login'))
        setup_token = os.environ.get('ADMIN_SETUP_TOKEN','')
        if len(setup_token)<32:
            return page('unconfigured'),503
        if request.method == 'POST':
            if limited('setup', maximum=10):
                return page('setup','Đã thử quá nhiều lần. Vui lòng đợi 15 phút.'),429
            supplied=request.form.get('setup_token','')
            if not hmac.compare_digest(setup_token, supplied):
                return page('setup','Mã thiết lập không đúng.'),403
            username=request.form.get('username','').strip().lower()
            name=request.form.get('display_name','').strip()
            error=password_error()
            if not valid_account(username,name) or error:
                return page('setup',error or 'Tên đăng nhập cần 3–40 ký tự: chữ thường, số, dấu . _ -; hãy nhập tên hiển thị.'),400
            with connect() as c:
                c.execute('SELECT pg_advisory_xact_lock(72905432)')
                if c.execute("SELECT id FROM manager_accounts WHERE role='owner' LIMIT 1").fetchone():
                    return redirect(url_for('manager_login'))
                c.execute("INSERT INTO manager_accounts(username,display_name,password_hash,role) VALUES(%s,%s,%s,'owner')",
                          (username,name,generate_password_hash(request.form['password'])))
            session.clear()
            return redirect(url_for('manager_login'))
        return page('setup')

    @app.route('/admin/accounts',methods=['GET','POST'])
    def manager_accounts():
        invitation=None
        error=None
        if request.method=='POST':
            username=request.form.get('username','').strip().lower()
            name=request.form.get('display_name','').strip()
            if not valid_account(username,name):
                error='Tên đăng nhập cần 3–40 ký tự: chữ thường, số, dấu . _ -; hãy nhập tên hiển thị.'
            else:
                token=secrets.token_urlsafe(32)
                with connect() as c:
                    result=c.execute('''INSERT INTO manager_accounts(username,display_name,invite_hash,invite_expires)
                        VALUES(%s,%s,%s,CURRENT_TIMESTAMP + interval '48 hours')
                        ON CONFLICT(username) DO NOTHING RETURNING id''',
                        (username,name,hashlib.sha256(token.encode()).hexdigest())).fetchone()
                if result:
                    invitation=url_for('manager_activate',_external=True)+'#'+token
                else:
                    error='Tên đăng nhập đã tồn tại.'
        with connect() as c:
            accounts=c.execute('SELECT id,username,display_name,role,active,password_hash IS NOT NULL AS activated FROM manager_accounts ORDER BY id').fetchall()
        return page('accounts',accounts=accounts,invitation=invitation,error=error)

    @app.post('/admin/accounts/<int:account_id>/disable')
    def manager_account_action(account_id):
        with connect() as c:
            c.execute("UPDATE manager_accounts SET active=0,version=version+1,invite_hash=NULL WHERE id=%s AND role!='owner'",(account_id,))
        return redirect(url_for('manager_accounts'))

    @app.route('/admin/activate',methods=['GET','POST'])
    def manager_activate():
        if request.method=='POST':
            if limited('activate',maximum=30):
                return page('activate','Đã thử quá nhiều lần. Vui lòng đợi 15 phút.'),429
            error=password_error()
            if error:
                return page('activate',error),400
            token=request.form.get('invite_token','')
            with connect() as c:
                user=c.execute('''UPDATE manager_accounts SET password_hash=%s,invite_hash=NULL,invite_expires=NULL,
                     version=version+1 WHERE invite_hash=%s AND active=1 AND invite_expires>CURRENT_TIMESTAMP
                     RETURNING id''',(generate_password_hash(request.form['password']),hashlib.sha256(token.encode()).hexdigest())).fetchone()
            if not user:
                return page('activate','Link đã hết hạn hoặc đã được sử dụng.'),400
            session.clear()
            return redirect(url_for('manager_login'))
        return page('activate')
