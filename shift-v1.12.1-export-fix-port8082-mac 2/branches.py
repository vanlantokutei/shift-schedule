"""Branch selection and owner-managed branch directory."""
from flask import abort, g, has_request_context, redirect, render_template, request, session, url_for


def branch_id():
    return getattr(g, 'branch', {}).get('id', 1) if has_request_context() else 1


def init_branches(connect):
    with connect() as c:
        c.execute('SELECT pg_advisory_xact_lock(72905433)')
        c.execute('''CREATE TABLE IF NOT EXISTS branches (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT UNIQUE NOT NULL, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)''')
        c.execute("INSERT INTO branches(id,name) VALUES(1,'ベト屋築地店') ON CONFLICT(id) DO NOTHING")
        c.execute("SELECT setval(pg_get_serial_sequence('branches','id'), GREATEST((SELECT max(id) FROM branches),1))")
        c.execute('ALTER TABLE staff ADD COLUMN IF NOT EXISTS branch_id INTEGER NOT NULL DEFAULT 1 REFERENCES branches(id)')
        c.execute('CREATE INDEX IF NOT EXISTS staff_branch_order ON staff(branch_id,sort_order,id)')
        c.execute('ALTER TABLE manager_accounts ADD COLUMN IF NOT EXISTS branch_id INTEGER NOT NULL DEFAULT 1 REFERENCES branches(id)')
        c.execute('''CREATE TABLE IF NOT EXISTS branch_kibo_deadlines (
            branch_id INTEGER NOT NULL REFERENCES branches(id), week_start TEXT NOT NULL,
            deadline TIMESTAMPTZ NOT NULL, PRIMARY KEY(branch_id,week_start))''')

        c.execute('''CREATE TABLE IF NOT EXISTS branch_kibo_settings (
            branch_id INTEGER PRIMARY KEY REFERENCES branches(id),
            always_open INTEGER NOT NULL DEFAULT 0 CHECK(always_open IN (0,1)))''')
        # Seed this store's setting once; other branches retain their own deadlines.
        c.execute('''INSERT INTO branch_kibo_settings(branch_id,always_open)
            SELECT id,1 FROM branches WHERE id=2 AND name=%s
            ON CONFLICT(branch_id) DO NOTHING''', ('デリメシ店',))


def install_branches(app, connect):
    @app.before_request
    def choose_branch():
        if request.endpoint in {'static', 'healthz', 'manager_login', 'manager_activate', 'manager_invite_info', 'manager_setup'}:
            return
        manager = getattr(g, 'manager', None)
        raw = request.values.get('branch')
        if raw is None:
            raw = session.get('branch_id', 1) if manager else 1
        try:
            selected = int(raw)
        except (TypeError, ValueError):
            abort(400)
        if manager and manager['role'] != 'owner':
            assigned = manager['branch_id']
            if request.values.get('branch') is not None and selected != assigned:
                abort(403)
            selected = assigned
        with connect() as c:
            row = c.execute('SELECT id,name FROM branches WHERE id=%s', (selected,)).fetchone()
        if not row:
            abort(404)
        g.branch = dict(row)
        # Existing LINE credentials, group and publications belong to Tsukiji.
        # Never expose that data or send it from another branch's page.
        if selected != 1 and (request.path.startswith(('/line/', '/admin/line', '/staff/'))
                              or request.endpoint == 'line_kibo_entry'):
            abort(409, description='LINE của chi nhánh này chưa được cấu hình. Hãy dùng trang lịch và đăng ký Kibo của chi nhánh.')

    @app.context_processor
    def branch_context():
        return {'current_branch': getattr(g, 'branch', {'id': 1, 'name': 'ベト屋築地店'})}

    @app.route('/admin/branches', methods=['GET', 'POST'])
    def branch_directory():
        if g.manager['role'] != 'owner':
            abort(403)
        error = None
        if request.method == 'POST':
            name = request.form.get('name', '').strip()
            if not 1 <= len(name) <= 80:
                error = 'Nhập tên chi nhánh từ 1 đến 80 ký tự.'
            else:
                with connect() as c:
                    c.execute('SELECT pg_advisory_xact_lock(72905433)')
                    row = c.execute('INSERT INTO branches(name) VALUES(%s) ON CONFLICT(name) DO NOTHING RETURNING id', (name,)).fetchone()
                if row:
                    session['branch_id'] = row['id']
                    return redirect(url_for('index', branch=row['id']))
                error = 'Chi nhánh này đã tồn tại.'
        with connect() as c:
            rows = c.execute('''SELECT b.id,b.name,count(s.id) AS staff_count FROM branches b
                LEFT JOIN staff s ON s.branch_id=b.id AND s.active=1 GROUP BY b.id,b.name ORDER BY b.id''').fetchall()
        return render_template('branches.html', branches=rows, error=error)

    @app.post('/admin/branches/select')
    def select_branch():
        if g.manager['role'] != 'owner':
            abort(403)
        session['branch_id'] = branch_id()
        return redirect(url_for('index', branch=branch_id()))
